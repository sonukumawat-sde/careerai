import 'package:flutter/material.dart';
import '../../../core/theme/app_gradients.dart';

/// Terms of Service + Privacy Policy — tabs ke saath.
class TermsPrivacyScreen extends StatefulWidget {
  final int initialTab; // 0 = Terms, 1 = Privacy
  const TermsPrivacyScreen({super.key, this.initialTab = 0});

  @override
  State<TermsPrivacyScreen> createState() => _TermsPrivacyScreenState();
}

class _TermsPrivacyScreenState extends State<TermsPrivacyScreen> {
  late int _tab;

  @override
  void initState() {
    super.initState();
    _tab = widget.initialTab;
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFFF8FAFC),
      appBar: AppBar(
        backgroundColor: const Color(0xFFF8FAFC),
        title: const Text('Legal'),
        centerTitle: true,
      ),
      body: Column(
        children: [
          // Tabs
          Padding(
            padding: const EdgeInsets.fromLTRB(20, 12, 20, 16),
            child: Container(
              padding: const EdgeInsets.all(4),
              decoration: BoxDecoration(
                color: const Color(0xFFEEF2F7),
                borderRadius: BorderRadius.circular(14),
              ),
              child: Row(
                children: [
                  _tabBtn('Terms of Service', 0),
                  _tabBtn('Privacy Policy', 1),
                ],
              ),
            ),
          ),
          Expanded(
            child: SingleChildScrollView(
              padding: const EdgeInsets.fromLTRB(20, 0, 20, 28),
              child: _tab == 0 ? _terms() : _privacy(),
            ),
          ),
        ],
      ),
    );
  }

  Widget _tabBtn(String label, int index) {
    final selected = _tab == index;
    return Expanded(
      child: GestureDetector(
        onTap: () => setState(() => _tab = index),
        child: AnimatedContainer(
          duration: const Duration(milliseconds: 200),
          padding: const EdgeInsets.symmetric(vertical: 10),
          decoration: BoxDecoration(
            gradient: selected ? AppGradients.buttonGradient : null,
            borderRadius: BorderRadius.circular(10),
          ),
          child: Center(
            child: Text(label,
                style: TextStyle(
                    color: selected ? Colors.white : const Color(0xFF64748B),
                    fontSize: 13,
                    fontWeight: FontWeight.w700)),
          ),
        ),
      ),
    );
  }

  Widget _terms() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        _lastUpdated(),
        _section('1. Acceptance of Terms',
            'By downloading, accessing, or using CareerAI, you agree to be bound by these Terms of Service. If you do not agree, please do not use the app.'),
        _section('2. Use of Service',
            'CareerAI provides AI-powered career tools including resume analysis, job listings, interview practice, and career coaching. You agree to use these services only for lawful purposes and in accordance with these terms.'),
        _section('3. User Accounts',
            'You are responsible for maintaining the confidentiality of your account credentials. You must provide accurate information and are responsible for all activity under your account.'),
        _section('4. Job Listings',
            'Job listings are aggregated from third-party sources. CareerAI does not guarantee the accuracy, availability, or legitimacy of any job posting. Applications are submitted directly to employers through their official channels.'),
        _section('5. AI-Generated Content',
            'Resume analysis, suggestions, and coaching responses are generated by AI and are for guidance only. We do not guarantee employment outcomes or the accuracy of AI suggestions.'),
        _section('6. Subscriptions',
            'Premium features are available through paid subscriptions. Payments are processed through the app store. Subscriptions auto-renew unless cancelled.'),
        _section('7. Prohibited Conduct',
            'You may not misuse the service, attempt unauthorized access, upload harmful content, or violate any applicable laws.'),
        _section('8. Termination',
            'We reserve the right to suspend or terminate accounts that violate these terms.'),
        _section('9. Changes to Terms',
            'We may update these terms from time to time. Continued use after changes constitutes acceptance.'),
        _section('10. Contact',
            'For questions about these terms, contact us at support@careerai.app'),
      ],
    );
  }

  Widget _privacy() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        _lastUpdated(),
        _section('1. Information We Collect',
            'We collect information you provide (name, email, phone, resume data, career preferences) and usage data (jobs viewed, applications, activity) to provide our services.'),
        _section('2. How We Use Your Data',
            'Your data is used to personalize AI recommendations, match you with relevant jobs, analyze your resume, and improve our services. We do not sell your personal data.'),
        _section('3. Resume & Documents',
            'Resumes you upload are processed by our AI to provide analysis. We store analysis results securely and associate them only with your account.'),
        _section('4. Data Storage',
            'Your data is stored securely using industry-standard encryption. We use trusted cloud infrastructure to protect your information.'),
        _section('5. Third-Party Services',
            'We use third-party services for job listings and AI processing. These services may process data as needed to provide functionality, subject to their own privacy policies.'),
        _section('6. Your Rights',
            'You can access, update, or delete your data anytime through the app. Deleting your account permanently removes all your data.'),
        _section('7. Data Sharing',
            'We only share data as necessary to provide services (e.g., submitting applications to employers you choose) or as required by law.'),
        _section('8. Security',
            'We implement reasonable security measures. However, no method of transmission is 100% secure.'),
        _section('9. Children',
            'CareerAI is not intended for users under 16 years of age.'),
        _section('10. Contact',
            'For privacy concerns, contact us at privacy@careerai.app'),
      ],
    );
  }

  Widget _lastUpdated() {
    return Container(
      margin: const EdgeInsets.only(bottom: 16),
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: AppBrand.violet.withValues(alpha: 0.06),
        borderRadius: BorderRadius.circular(10),
      ),
      child: const Text('Last updated: January 2026',
          style: TextStyle(
              color: AppBrand.violet,
              fontSize: 12,
              fontWeight: FontWeight.w700)),
    );
  }

  Widget _section(String title, String body) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 20),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(title,
              style: const TextStyle(
                  color: Color(0xFF0F172A),
                  fontSize: 15,
                  fontWeight: FontWeight.w800)),
          const SizedBox(height: 8),
          Text(body,
              style: const TextStyle(
                  color: Color(0xFF475569), fontSize: 13.5, height: 1.6)),
        ],
      ),
    );
  }
}